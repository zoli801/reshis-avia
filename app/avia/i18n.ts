const templateEntries=Object.entries(english).filter(([key])=>/\{\d+\}/.test(key));
const escapePattern=(value:string)=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
function templateTranslation(value:string,from:string,to:string):string|null {
 const keys=[...from.matchAll(/\{(\d+)\}/g)].map(match=>Number(match[1]));
 const pattern=from.split(/\{\d+\}/).map(escapePattern).join('(.*?)');
 const match=value.match(new RegExp('^'+pattern+'$'));
 if(!match)return null;
 const replacements=new Map(keys.map((key,index)=>[key,match[index+1]]));
 return to.replace(/\{(\d+)\}/g,(_,index)=>replacements.get(Number(index))??'');
}
