/** Locale selection and server-owned copy only. Never translate user-authored data. */
export type Language='ru'|'en';
export function requestLanguage(request:Request):Language {
  const explicit=new URL(request.url).searchParams.get('lang');
  if(explicit==='en'||explicit==='ru')return explicit;
  return /^en(?:[-,;]|$)/i.test(request.headers.get('Accept-Language')??'')?'en':'ru';
}
